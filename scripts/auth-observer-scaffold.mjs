/** Deterministic, read-only product-observer scaffold for installed AUTH contracts. */
import { lstat, readFile, realpath, rename, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { CAPABILITIES } from './auth-capability-catalog.mjs';

export const OBSERVER_INPUT = '.auth-kit/observer-input.json';
export const OBSERVER_PATH = '.auth-kit/observe.mjs';
export const LEGACY_OBSERVER = `// Replace before establishment with the product-owned, read-only evidence collector.\n// Read binding context JSON from stdin; emit {adapter, binding, independence}.\nthrow new Error('PRODUCT_OBSERVER_REQUIRED');\n`;

const json = value => `${JSON.stringify(value, null, 2)}\n`;
const scaffoldSource = `// Generated by AUTH. Product-owned, read-only observation seam.\nimport { readFile } from 'node:fs/promises';\nconst chunks=[];for await(const chunk of process.stdin)chunks.push(chunk);\nconst binding=JSON.parse(Buffer.concat(chunks).toString('utf8'));\nconst input=JSON.parse(await readFile(new URL('./observer-input.json',import.meta.url),'utf8'));\nif(input.schemaVersion!==1||input.adapter?.schemaVersion!==1||input.adapter?.productId!==binding.productId)throw new Error('PRODUCT_OBSERVER_INPUT_INVALID');\nconst adapter={...input.adapter,revision:binding.revision};\nprocess.stdout.write(JSON.stringify({binding,adapter,independence:input.independence||{wizardStopped:false,authOrchestrationRequests:null,runtimePassed:false,evidence:[]}}));\n`;

export function productObserverScaffold(productId) {
  if (typeof productId !== 'string' || !productId.trim()) throw new Error('PRODUCT_OBSERVER_PRODUCT_REQUIRED');
  return {
    source: scaffoldSource,
    input: {
      schemaVersion: 1,
      instructions: 'Replace only observation values with fresh, secret-free product evidence. Do not add runtime/provider/session implementation here.',
      adapter: {
        schemaVersion: 1,
        productId,
        revision: 'BOUND_BY_AUTH_AT_RUNTIME',
        capabilities: Object.fromEntries(CAPABILITIES.map(capability => [capability.id, {
          applicability: 'INDETERMINATE',
          implementation: 'INDETERMINATE',
          evidence: [],
          checks: Object.fromEntries(capability.checks.map(check => [check, null])),
        }])),
      },
      independence: { wizardStopped: false, authOrchestrationRequests: null, runtimePassed: false, evidence: [] },
    },
  };
}

async function regularFile(file) {
  const entry = await lstat(file);
  if (entry.isSymbolicLink() || !entry.isFile()) throw new Error('PRODUCT_OBSERVER_PATH_INVALID');
  return entry;
}

export async function installProductObserverScaffold(root, productId, { authorized = false } = {}) {
  if (!authorized) throw new Error('PRODUCT_OBSERVER_AUTHORIZATION_REQUIRED');
  root = await realpath(root);
  const contractPath = path.join(root, '.auth-kit', 'contract.json');
  await regularFile(contractPath);
  const contract = JSON.parse(await readFile(contractPath, 'utf8'));
  if (contract.productId !== productId || contract.state !== 'UNESTABLISHED') throw new Error('PRODUCT_OBSERVER_CONTRACT_NOT_EDITABLE');
  const observerPath = path.join(root, OBSERVER_PATH);
  await regularFile(observerPath);
  const existing = await readFile(observerPath, 'utf8');
  const scaffold = productObserverScaffold(productId);
  if (existing !== LEGACY_OBSERVER && existing !== scaffold.source) throw new Error('PRODUCT_OBSERVER_EXISTING_CUSTOM_COLLECTOR');
  const inputPath = path.join(root, OBSERVER_INPUT);
  try {
    await regularFile(inputPath);
    const input = JSON.parse(await readFile(inputPath, 'utf8'));
    if (existing === scaffold.source && input?.adapter?.productId === productId) return { productId, observer: OBSERVER_PATH, input: OBSERVER_INPUT, state: 'ALREADY_SCAFFOLDED_UNESTABLISHED' };
    throw new Error('PRODUCT_OBSERVER_INPUT_EXISTS');
  } catch (error) { if (error?.code !== 'ENOENT') throw error; }
  const observerTemp = `${observerPath}.tmp-${randomUUID()}`;
  const inputTemp = `${inputPath}.tmp-${randomUUID()}`;
  await writeFile(observerTemp, scaffold.source, { flag: 'wx' });
  await writeFile(inputTemp, json(scaffold.input), { flag: 'wx' });
  try {
    await rename(inputTemp, inputPath);
    await rename(observerTemp, observerPath);
  } catch (error) {
    await rm(observerTemp, { force: true }).catch(() => {});
    await rm(inputTemp, { force: true }).catch(() => {});
    await rm(inputPath, { force: true }).catch(() => {});
    throw error;
  }
  return { productId, observer: OBSERVER_PATH, input: OBSERVER_INPUT, state: 'SCAFFOLDED_UNESTABLISHED' };
}
